-- | @<prefix>.Generated.Enums@: a Haskell sum type per IDL enum.
module DomGen.Emit.Enums
  ( emitEnums
  ) where

import qualified Data.Map.Strict as M
import qualified Data.Set as S
import Data.Text (Text)
import qualified Data.Text as T

import DomGen.Emit.Types (Flavour (..))
import DomGen.Env
import DomGen.Model
import DomGen.Names

-- | Constructor names: enum name plus the camel cased value (the old
-- convention: @CanvasWindingRuleNonzero@, empty string -> the enum name).
constructors :: EnumDef -> [(Text, Text)]
constructors e = go S.empty (enumValues e)
  where
    go _ [] = []
    go used (v : vs) =
      let base = enumName e <> conIdent v
          c = freshName used [base]
      in (c, v) : go (S.insert c used) vs

emitEnums :: Flavour -> Env -> Text
emitEnums fl env = T.unlines $
  [ "{-# LANGUAGE OverloadedStrings #-}"
  , "{-# OPTIONS_GHC -fno-warn-unused-imports #-}"
  , "-- | Generated by dom-gen from webref IDL. Do not edit."
  , "module " <> modName
  , "       (" <> T.intercalate ", " exports <> ")"
  , "       where"
  , "import Prelude ((.), (>>=), (<$>), Show, Read, Eq, Ord, Bounded, Enum, Maybe(..))"
  , "import qualified Prelude as P"
  , "import Data.Typeable (Typeable)"
  ] <> imports <> [""] <> concatMap (enumBlock fl) enums
  where
    modName = case fl of
      JSaddle -> "JSDOM.Generated.Enums"
      JSFFI -> "GHCJS.DOM.JSFFI.Generated.Enums"
    imports = case fl of
      JSaddle -> [ "import Language.Javascript.JSaddle (JSM, JSString, ToJSVal(..), FromJSVal(..))" ]
      JSFFI ->
        [ "import GHCJS.Types (JSString)"
        , "import GHCJS.Marshal (ToJSVal(..), FromJSVal(..))"
        , "import GHCJS.Marshal.Pure (PToJSVal(..), PFromJSVal(..))" ]
    enums = [ e | n <- S.toAscList (envEnums env), Just e <- [M.lookup n (domEnums (envDom env))] ]
    exports = concat [ (enumName e <> "(..)") : [ "js_" <> c | (c, _) <- constructors e ] | e <- enums ]

enumBlock :: Flavour -> EnumDef -> [Text]
enumBlock fl e =
  [ "-- | <https://developer.mozilla.org/en-US/docs/Web/API " <> n <> "> (" <> enumSpec e <> ")"
  , "data " <> n <> " = " <> T.intercalate "\n    | " (map fst cs)
  , "    deriving (Show, Read, Eq, Ord, Bounded, Enum, Typeable)"
  , ""
  ] <> instances <> concat
  [ [ "js_" <> c <> " :: JSString"
    , "js_" <> c <> " = " <> T.pack (show (T.unpack v)) ]
  | (c, v) <- cs ] <> [""]
  where
    n = enumName e
    cs = constructors e
    toString = [ "    " <> c <> " -> js_" <> c | (c, _) <- cs ]
    table = "[" <> T.intercalate ", " [ "(js_" <> c <> ", " <> c <> ")" | (c, _) <- cs ] <> "]"
    instances = case fl of
      JSaddle ->
        [ "instance ToJSVal " <> n <> " where"
        , "  toJSVal x = toJSVal (case x of" ] <> toString <>
        [ "    )"
        , ""
        , "instance FromJSVal " <> n <> " where"
        , "  fromJSVal x = (>>= (`P.lookup` table)) <$> (fromJSVal x :: JSM (Maybe JSString))"
        , "    where table = " <> table
        , "  fromJSValUnchecked x = fromJSVal x >>= P.maybe (P.error \"Unexpected " <> n <> " value\") P.return"
        , "" ]
      JSFFI ->
        [ "instance PToJSVal " <> n <> " where"
        , "  pToJSVal x = pToJSVal (case x of" ] <> toString <>
        [ "    )"
        , ""
        , "instance ToJSVal " <> n <> " where"
        , "  toJSVal = P.return . pToJSVal"
        , ""
        , "instance PFromJSVal " <> n <> " where"
        , "  pFromJSVal x = P.maybe (P.error \"Unexpected " <> n <> " value\") P.id (P.lookup (pFromJSVal x :: JSString) table)"
        , "    where table = " <> table
        , ""
        , "instance FromJSVal " <> n <> " where"
        , "  fromJSVal x = P.return (P.lookup (pFromJSVal x :: JSString) table)"
        , "    where table = " <> table
        , "  fromJSValUnchecked = P.return . pFromJSVal"
        , "" ]
