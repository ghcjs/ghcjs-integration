-- | The data for the browser existence test (ghcjs-dom-tests): every bound
-- interface and member with the engines BCD says ship it, so the test can
-- check the bindings against what the browser actually exposes.
--
-- One line per check, tab separated:
--
-- > kind  owners  name  engines
--
-- * kind: @I@ interface object (a global), @P@ instance member, @S@ static
--   member, constant or namespace member (on the interface object).
-- * owners: @|@ separated interfaces to look on (for instance members also
--   the typed descendants; for a mixin its including interfaces); for @I@
--   the global name itself.
-- * engines: space separated, one per engine with stable support in BCD:
--   its letter (@c@ chromium, @g@ gecko, @w@ webkit) then BCD's
--   version_added for Chrome, Firefox or Safari (empty if only @true@),
--   e.g. @c158 g129 w17.4@, with a @~@ before the version when the support
--   is only partial (e.g. @g~141@); @?@ when BCD has no data.
--
-- The test decides where an owner's instance members live (the prototype,
-- the global object for @[Global]@ interfaces, a known instance for
-- @[LegacyUnforgeable]@ ones).
module DomGen.Emit.Existence (emitExistence) where

import qualified Data.Map.Strict as M
import Data.Maybe (fromMaybe)
import qualified Data.Set as S
import Data.Text (Text)
import qualified Data.Text as T

import DomGen.Emit.Common (moduleDefinitions)
import DomGen.Env
import DomGen.Model

-- | Exposed in Window (or no [Exposed]: a mixin, which takes its includers').
exposedInWindow :: Definition -> Bool
exposedInWindow d = case extAttrRhs "Exposed" (defExtAttrs d) of
  [] -> not (hasExtAttr "Exposed" (defExtAttrs d))
  ws -> any (`elem` ["Window", "*"]) ws

engineLetters :: Maybe Compat -> Text
engineLetters = \case
  Nothing -> "?"
  Just c -> T.unwords
    [ T.cons l (if e `elem` cPartial c then "~" <> v else v)
    | (e, l) <- [("chromium", 'c'), ("gecko", 'g'), ("webkit", 'w')], Just v <- [lookup e (cSince c)] ]

-- | Haskell module @Existence.Spec@ with the check lines as one string.
emitExistence :: Env -> Text
emitExistence env = T.unlines $
  [ "-- | Generated by dom-gen (DomGen.Emit.Existence). Do not edit."
  , "module Existence.Spec (existenceSpec) where"
  , ""
  , "import Data.Text (Text)"
  , "import qualified Data.Text as T"
  , ""
  , "-- | kind, owners, name, engines (tab separated; see DomGen.Emit.Existence)."
  , "-- (One string literal: a list of thousands of literals compiles slowly.)"
  , "existenceSpec :: [Text]"
  , "existenceSpec = T.lines $ T.pack"
  ] <> zipWith3 (\i l end -> (if i == (0 :: Int) then "  \"" else "  \\") <> esc l <> end)
         [0 ..] specLines (replicate (length specLines - 1) "\\n\\" <> ["\""])
  where
    specLines = concatMap linesFor defs
    -- a multi-line string literal using string gaps
    esc = T.concatMap (\case '\t' -> "\\t"; '"' -> "\\\""; '\\' -> "\\\\"; c -> T.singleton c)
    defs = [ d | d <- moduleDefinitions env, defKind d /= KDictionary, exposedInWindow d ]
    typed = S.fromList (map defName defs)
    line k os n e = T.intercalate "\t" [k, T.intercalate "|" os, n, e]

    linesFor d =
      [ line "I" [defName d] (defName d) (engineLetters (defBcd d))
      | defKind d /= KMixin
      , not (hasExtAttr "LegacyNoInterfaceObject" (defExtAttrs d)) ]
      <> concatMap (memberLine d) (dedupe (defMembersIncluded env d))

    -- A member is checked once by name (overloads share one property).
    dedupe = M.elems . M.fromListWith (\_ a -> a)
      . map (\m -> ((memSpecial m == "static", fromMaybe "" (memName m)), m))
      . filter (\m -> memKind m `elem` [MOperation, MAttribute, MConst] && maybe False (not . T.null) (memName m))

    memberLine d m = case memName m of
      Nothing -> []
      Just n ->
        let direct
              | defKind d == KMixin = [ o | o <- defIncludedBy d, S.member o typed ]
              | otherwise = [defName d]
            onObject = defKind d == KNamespace || memSpecial m == "static" || memKind m == MConst
            kind = if onObject then "S" else "P"
            -- Instances are of some concrete interface, and engines may define
            -- a member on the subclasses (Chrome: AbstractRange.startContainer
            -- is on Range.prototype and StaticRange.prototype).
            owners
              | onObject = direct
              | otherwise = direct <> [ c | o <- direct, c <- descendants env o, S.member c typed, c `notElem` direct ]
            -- not bound: handlers are used through events, and the dashed CSS
            -- spellings are aliases of the camel case ones
            isHandlerAttr = memKind m == MAttribute && maybe False isEventHandlerType (memType m)
            -- member level [Exposed=DedicatedWorker] (createSyncAccessHandle,
            -- MediaSource.handle) is not there to find in a Window
            workerOnly = case extAttrRhs "Exposed" (memExtAttrs m) of
              [] -> False
              ws -> not (any (`elem` ["Window", "*"]) ws)
        in [ line kind owners n (engineLetters (memBcd m))
           | not (null owners), not isHandlerAttr, not ("-" `T.isInfixOf` n), not workerOnly ]
