-- | The jsaddle backend (jsaddle-dom): members are reached with jsaddle's
-- @js@ / @jss@ / @jsf@ / @new@, so the same code works with native GHC
-- (through a JavaScript context) and in the browser.
module DomGen.Emit.JSaddle
  ( jsaddleBackend
  , emitCallbackModule
  ) where

import qualified Data.Text as T
import Data.Text (Text)

import DomGen.Emit.Common
import DomGen.Env

jsaddleBackend :: Backend
jsaddleBackend = Backend
  { beRoot = "JSDOM"
  , beGenerated = "JSDOM.Generated"
  , bePragmas =
      [ "{-# LANGUAGE PatternSynonyms #-}"
      , "{-# LANGUAGE ImplicitParams, ConstraintKinds, KindSignatures #-}"
      , "{-# OPTIONS_GHC -fno-warn-unused-imports #-}"
      ]
  , beImports = standardImports
  , beCall = call
  , beConvert = convert
  , beUnchecked = unchecked
  , beExtraExports = const []
  }

standardImports :: [Text]
standardImports =
  [ "import Prelude ((.), (==), (>>=), (<$>), (++), Bool(..), Maybe(..), IO, Int, Word, Double, Float)"
  , "import qualified Prelude as P"
  , "import Control.Monad (void)"
  , "import Control.Lens.Operators ((^.))"
  , "import Language.Javascript.JSaddle (JSM, JSVal, JSString, toJSVal, valToBool, valToNumber, js, jss, jsf, jsg, new, function, asyncFunction, jsUndefined, jsNull)"
  ]

call :: Call -> ([Text], Text)
call Call {..} = ([], resolvePromise expr)
  where
    obj = case cTarget of
      TSelf e _ -> e
      TGlobal g -> "(jsg \"" <> g <> "\")"
    expr = case cAccess of
      AMethod js -> obj <> " ^. jsf \"" <> js <> "\" " <> jsArgs cArgs
      AGet js -> obj <> " ^. js \"" <> js <> "\""
      ASet js -> obj <> " ^. jss \"" <> js <> "\" (toJSVal val)"
      ANew -> "new " <> obj <> " " <> jsArgs cArgs
      ANewObject names ->
        "(new (jsg \"Object\") () >>= \\o -> "
          <> T.concat [ "(o ^. jss \"" <> n <> "\" (toJSVal " <> aName a <> ")) P.>> " | (n, a) <- zip names cArgs ]
          <> "P.return o)"
    resolvePromise e = case cResult of
      HPromise _ -> "((" <> e <> ") >>= readPromise)"
      _ -> e

-- | The argument list for jsf / new.  An omitted optional argument is
-- passed as @undefined@ (not @null@, which would e.g. become 0 for a
-- number).
jsArgs :: [Arg] -> Text
jsArgs [] = "()"   -- an empty list's element type would be ambiguous
jsArgs args =
  let fixed = [ case aMode a of
                  Optional -> "P.maybe (P.return jsUndefined) toJSVal " <> aName a
                  _ -> "toJSVal " <> aName a
              | a <- args, aMode a /= Variadic ]
      variadic = [ aName a | a <- args, aMode a == Variadic ]
      list = "[" <> T.intercalate ", " fixed <> "]" <> T.concat [ " ++ P.map toJSVal " <> v | v <- variadic ]
  in if null variadic then list else "(" <> list <> ")"

-- | Convert @JSM JSVal@ to the result type.
convert :: HTy -> Text -> Text
convert ty e = case ty of
  HUnit -> "(void (" <> e <> "))"
  HBool -> "((" <> e <> ") >>= valToBool)"
  HNum "Double" -> "((" <> e <> ") >>= valToNumber)"
  HNum "Float" -> "(P.realToFrac <$> ((" <> e <> ") >>= valToNumber))"
  HNum _ -> "(P.round <$> ((" <> e <> ") >>= valToNumber))"
  HAny -> e
  HMaybe HString -> "((" <> e <> ") >>= fromMaybeJSString)"
  -- The `Maybe a` instance maps null/undefined to Nothing.  (`fromJSVal` at
  -- type `a` would give e.g. `Just False` / `Just 0` for null.)
  _ -> "((" <> e <> ") >>= fromJSValUnchecked)"

unchecked :: HTy -> Text -> Text
unchecked ty e = case ty of
  HMaybe t@HBool -> convert t e
  HMaybe t@(HNum _) -> convert t e
  _ -> "((" <> e <> ") >>= fromJSValUnchecked)"

-- | @newFoo@, @newFooSync@, @newFooAsync@ for a callback (or callback
-- interface).  The callback's return value is ignored, as before.
emitCallbackModule :: Env -> Text -> GenModule
emitCallbackModule env n = GenModule n text
  where
    (names, tys, spec) = callbackArgs env n
    fnTy = T.intercalate " -> " (map hsTyCon tys <> ["JSM ()"])
    pat = case names of
      [] -> "_"
      _ -> "(" <> T.intercalate " : " (names <> ["_"]) <> ")"
    convs = [ "\n          " <> v <> "' <- " <> fromJS t v | (v, t) <- zip names tys ]
    lam = "(\\ _ _ args -> case args ++ P.repeat jsUndefined of\n        " <> pat <> " -> do"
          <> T.concat convs
          <> "\n          callback " <> T.unwords (map (<> "'") names) <> ")"
    mk suffix fn = T.unlines
      [ "new" <> n <> suffix <> " :: (MonadDOM m) => (" <> fnTy <> ") -> m " <> n
      , "new" <> n <> suffix <> " callback = liftDOM (" <> n <> " . Callback <$> " <> fn <> " " <> lam <> ")"
      ]
    exports = ["new" <> n, "new" <> n <> "Sync", "new" <> n <> "Async", n]
    text = T.unlines
      [ "{-# OPTIONS_GHC -fno-warn-unused-imports #-}"
      , "-- | Generated by dom-gen from " <> spec <> " (webref). Do not edit."
      , "module JSDOM.Generated." <> n
      , "       (" <> T.intercalate ", " exports <> ")"
      , "       where"
      ] <> T.unlines standardImports
        <> "import JSDOM.Types\nimport JSDOM.Generated.Enums\n\n"
        <> T.intercalate "\n" [mk "" "function", mk "Sync" "function", mk "Async" "asyncFunction"]

fromJS :: HTy -> Text -> Text
fromJS t v = case t of
  HAny -> "P.return " <> v
  HBool -> "valToBool " <> v
  HNum "Double" -> "valToNumber " <> v
  HNum "Float" -> "P.realToFrac <$> valToNumber " <> v
  HNum _ -> "P.round <$> valToNumber " <> v
  _ -> "fromJSValUnchecked " <> v   -- for Maybe: null/undefined -> Nothing
