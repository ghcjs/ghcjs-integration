-- JS level

data Reason = NotInSpecs | Unsupported [Text] | StillPresent
  deriving (Eq, Ord)

jsLevel :: Env -> [Text]
jsLevel env =
  [ "## Removed JavaScript members"
  , ""
  , "Members of the old bindings that the new ones do not bind, by interface."
  , "*not in specs*: no current specification defines it (often WebKit-only or"
  , "removed from the web platform). *support*: it is in a specification but"
  , "ships in fewer than two engines (the engines listed have it)."
  , ""
  , "| | interfaces | members |"
  , "|---|---:|---:|"
  , "| interface not in specs | " <> tshow (length goneIfaces) <> " | " <> tshow (sum (map (S.size . snd) goneIfaces)) <> " |"
  , "| interface filtered by support | " <> tshow (length filteredIfaces) <> " | " <> tshow (sum (map (S.size . snd) filteredIfaces)) <> " |"
  , "| member not in specs | | " <> tshow (count NotInSpecs) <> " |"
  , "| member filtered by support | | " <> tshow (length [ () | (_, _, Unsupported _) <- memberLoss ]) <> " |"
  , ""
  , "### Interfaces renamed"
  , ""
  ] <> [ "* `" <> i <> "` → `" <> n <> "`" | (i, n) <- renamed ] <>
  [ ""
  , "### Interfaces not in current specs"
  , ""
  , T.intercalate ", " [ "`" <> i <> "`" | (i, _) <- goneIfaces, not (M.member i renamedMap) ]
  , ""
  , "### Interfaces filtered by browser support"
  , ""
  ] <> [ "* `" <> i <> "` (" <> engines (defBcd d) <> ")" | (i, _) <- filteredIfaces, Just d <- [M.lookup i defs] ] <>
  [ ""
  , "### Members removed from interfaces that remain"
  , ""
  ] <> concat
  [ ["* `" <> i <> "`: " <> T.intercalate ", " (map fmt ms)]
  | (i, ms) <- M.toList (M.fromListWith (flip (<>)) [ (i, [(n, r)]) | (i, n, r) <- memberLoss ]) ] <>
  [ "" ]
  where
    bl = envBaseline env
    defs = envDefs env
    typed = envTyped env <> envCallbacks env
    tshow = T.pack . show
    oldIfaces = M.toList (blMembers bl)
    goneIfaces = [ (i, ms) | (i, ms) <- oldIfaces, not (M.member i defs), not (M.member i (domCallbacks (envDom env))) ]
    -- e.g. ANGLEInstancedArrays -> ANGLE_instanced_arrays (WebGL extensions
    -- are now named after the extension)
    key = T.toLower . T.filter (/= '_')
    newByKey = M.fromList [ (key n, n) | n <- S.toList typed ]
    renamed = [ (i, n) | (i, _) <- goneIfaces, Just n <- [M.lookup (key i) newByKey] ]
    renamedMap = M.fromList renamed
    filteredIfaces = [ (i, ms) | (i, ms) <- oldIfaces, M.member i defs, not (S.member i typed) ]
    memberLoss =
      [ (i, n, r)
      | (i, ms) <- oldIfaces, S.member i typed, Just d <- [M.lookup i defs]
      , n <- S.toList ms
      , let r = reason d n
      , r /= StillPresent ]
    count r = length [ () | (_, _, r') <- memberLoss, r' == r ]
    fmt (n, r) = "`" <> n <> "`" <> case r of
      Unsupported es -> " (support: " <> (if null es then "none" else T.intercalate ", " es) <> ")"
      _ -> ""
    engines = maybe "no BCD data" (\c -> if null (cEngines c) then "no engine" else T.intercalate ", " (cEngines c))
    -- the member named n (JS name, "constructor", "on<event>", or a const)
    -- of d, its mixins and ancestors
    reason d n =
      let candidates = [ (dd, m) | dd <- d : mixinsAndAncestors d, m <- defMembers dd, matches n m ]
      in case candidates of
           [] | "on" `T.isPrefixOf` n && eventKnown (T.drop 2 n) -> StillPresent
              | otherwise -> NotInSpecs
           _ | any (\(dd, m) -> memberIncluded env dd m) candidates -> StillPresent
             | otherwise -> Unsupported (concat [ maybe [] cEngines (memBcd m) | (_, m) <- take 1 candidates ])
    matches n m = case memKind m of
      MConstructor -> n == "constructor"
      _ -> memName m == Just n
    mixinsAndAncestors d =
      [ x | a <- defName d : ancestors env (defName d), Just ad <- [M.lookup a defs]
          , x <- ad : [ mx | mn <- defIncludes ad, Just mx <- [M.lookup mn defs] ] ]
    eventKnown ty = any ((== ty) . evType) (domEvents (envDom env))

