-- | @dom-gen apidiff@: what changed between the old (domconv-webkit) and
-- new (webref) bindings, with a reason for every removal.
--
--   * JS level: every member the old bindings exposed (from the baseline)
--     is looked up in the new model.  A member that is gone is either not
--     in the current specs, or filtered out by browser support (BCD).
--   * Haskell level: the two hoogle dumps are compared: names removed,
--     added, moved to another module, and type changes.
module DomGen.ApiDiff
  ( apiDiff
  ) where

import Data.Char (isAlphaNum, isUpper)
import Data.List (sortOn)
import qualified Data.Map.Strict as M
import Data.Maybe (fromMaybe)
import qualified Data.Set as S
import Data.Text (Text)
import qualified Data.Text as T
import qualified Data.Text.IO as T

import DomGen.Baseline
import DomGen.Env
import DomGen.Model

-- | @apiDiff env oldHoogle newHoogle out@
apiDiff :: Env -> FilePath -> FilePath -> FilePath -> IO ()
apiDiff env oldPath newPath out = do
  old <- parseHoogle <$> T.readFile oldPath
  new <- parseHoogle <$> T.readFile newPath
  let report = T.unlines $
        [ "# jsaddle-dom / ghcjs-dom 0.10 API changes"
        , ""
        , "Generated by `dom-gen apidiff` from the 0.9.9.3 baseline. Inputs: "
            <> "webref and browser-compat-data as pinned in `dom-gen/inputs.nix`."
        , "" ]
        <> jsLevel env
        <> hsLevel old new
  T.writeFile out report
  putStrLn ("wrote " <> out)

