-- Haskell level (hoogle dumps)

-- | name -> [(module, normalised declaration)]
type Decls = M.Map Text [(Text, Text)]

parseHoogle :: Text -> Decls
parseHoogle = go "" M.empty . T.lines
  where
    go _ acc [] = acc
    go m acc (l : ls)
      | "module " `T.isPrefixOf` l = go (T.strip (T.drop 7 l)) acc ls
      | T.null l || "--" `T.isPrefixOf` l || "@" `T.isPrefixOf` l = go m acc ls
      | "instance " `T.isPrefixOf` l = go m acc ls
      | otherwise = case declName l of
          Just n -> go m (M.insertWith (flip (<>)) n [(publicModule m, normalise l)] acc) ls
          Nothing -> go m acc ls
    -- Types and values live in separate namespaces (a newtype and its
    -- constructor share a name), so type level names get a suffix.
    declName l =
      let ws = T.words l
          isType = case ws of
            (w : _) -> w `elem` ["data", "newtype", "class", "type"]
            [] -> False
          -- `class (C a, D a) => E a`: the name follows the context
          ws0 = case break (== "=>") ws of
            (pre, _ : post) | take 1 pre == ["class"] -> "class" : post
            _ -> ws
          ws' = dropWhile (`elem` ["pattern", "data", "newtype", "class", "type", "family"]) ws0
          suffix = if isType then " (type)" else ""
      in case ws' of
           (w : _) -> Just (T.dropAround (`elem` ['[', ']', '(', ')']) w <> suffix)
           [] -> Nothing

-- | JSDOM.Generated.X and JSDOM.Custom.X are both re-exported as JSDOM.X.
publicModule :: Text -> Text
publicModule m = fromMaybe m $
  ("JSDOM." <>) <$> (T.stripPrefix "JSDOM.Generated." m `orElse` T.stripPrefix "JSDOM.Custom." m)
  where orElse a b = maybe b Just a

-- | Remove module qualifiers (haddock writes some names qualified).
normalise :: Text -> Text
normalise = T.unwords . map unqualify . T.words
  where
    unqualify w =
      let (pre, rest) = T.span (not . isUpper) w
      in pre <> stripQual rest
    stripQual t = case T.breakOn "." t of
      (a, b) | not (T.null b), not (T.null a), T.all (\c -> isAlphaNum c || c == '_') a
             , maybe False (isUpper . fst) (T.uncons a)
             , Just rest <- T.stripPrefix "." b, maybe False ((\c -> isUpper c || isAlphaNum c) . fst) (T.uncons rest)
             -> stripQual rest
      _ -> t

hsLevel :: Decls -> Decls -> [Text]
hsLevel old new =
  [ "## Haskell API"
  , ""
  , "| | names |"
  , "|---|---:|"
  , "| removed | " <> tshow (length removed) <> " |"
  , "| moved to another module | " <> tshow (length moved) <> " |"
  , "| type changed | " <> tshow (length changed) <> " |"
  , "| added | " <> tshow (length added) <> " |"
  , ""
  , "### Type changes (same module and name)"
  , ""
  , "<details><summary>" <> tshow (length changed) <> " changes</summary>"
  , ""
  ] <> concat [ ["* `" <> m <> "." <> n <> "`", "  * old: `" <> o <> "`", "  * new: `" <> nw <> "`"] | (m, n, o, nw) <- changed ] <>
  [ ""
  , "</details>"
  , ""
  , "### Moved (name now defined in a different module)"
  , ""
  , "<details><summary>" <> tshow (length moved) <> " names</summary>"
  , ""
  ] <> [ "* `" <> n <> "`: " <> T.intercalate ", " om <> " → " <> T.intercalate ", " nm | (n, om, nm) <- moved ] <>
  [ ""
  , "</details>"
  , ""
  , "### Removed Haskell names, by old module"
  , ""
  , "<details><summary>" <> tshow (length removed) <> " names</summary>"
  , ""
  ] <> [ "* `" <> m <> "`: " <> T.intercalate ", " (map (\n -> "`" <> n <> "`") ns)
       | (m, ns) <- M.toList (M.fromListWith (flip (<>)) [ (m, [n]) | (m, n) <- removed ]) ] <>
  [ ""
  , "</details>"
  , "" ]
  where
    tshow = T.pack . show
    removed = sortOn id [ (m, n) | (n, ds) <- M.toList old, not (M.member n new), (m, _) <- take 1 ds ]
    added = [ n | n <- M.keys new, not (M.member n old) ]
    moved =
      [ (n, om, nm)
      | (n, ods) <- M.toList old, Just nds <- [M.lookup n new]
      , let om = S.toList (S.fromList (map fst ods)); nm = S.toList (S.fromList (map fst nds))
      , S.null (S.intersection (S.fromList om) (S.fromList nm)) ]
    changed =
      [ (m, n, o, nw)
      | (n, ods) <- M.toList old, Just nds <- [M.lookup n new]
      , (m, o) <- ods, Just nw <- [lookup m nds], o /= nw ]
